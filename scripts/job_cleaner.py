def normalize_positions(raw):
    if not raw:
        return ''
    s = str(raw).strip()
    parts = [p.strip() for p in re.split(r'[,，、;；]', s) if p.strip()]
    parts = [re.sub(r'\.{2,}$', '', p).strip() for p in parts]
    parts = [p for p in parts if p]
    return ','.join(parts)

