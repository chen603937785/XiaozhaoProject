def normalize_recruit_types(raw):
    """拆分多值并映射到标准类型，返回 (标准类型逗号串, 原始值)"""
    if not raw:
        return '', raw or ''
    s = str(raw).strip()
    for k, v in TYPO_FIX.items():
        if k in s:
            s = s.replace(k, v)
    parts = re.split(r'[,，、/]', s)
    result = set()
    for p in parts:
        p = p.strip()
        if not p:
            continue
        result.add(RECRUIT_TYPE_MAP.get(p, p))
    ordered = [t for t in RECRUIT_TYPES if t in result]
    for r in result:
        if r not in ordered:
            ordered.append(r)
    return ','.join(ordered), s

