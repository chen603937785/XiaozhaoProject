/* Build the desktop UI around the EXACT extension field/control modules. */
const fs=require('fs'),path=require('path'),vm=require('vm');
const root=path.resolve(__dirname,'..');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'autofill-extension/manifest.json'),'utf8'));
const modules=manifest.content_scripts.find(x=>x.js.includes('engine.js')).js.filter(x=>x!=='content.js');
const license=fs.readFileSync(path.join(root,'autofill-extension/vendor/LICENSE'),'utf8');
const notice=fs.readFileSync(path.join(root,'autofill-extension/vendor/NOTICE.md'),'utf8');
const parts=modules.map(file=>'\n/* Shared extension module: '+file+' */\n'+fs.readFileSync(path.join(root,'autofill-extension',file),'utf8'));
const ui=fs.readFileSync(path.join(root,'campus-job-desktop/src-tauri/autofill-desktop.js'),'utf8');
const out='/* Generated by scripts/build_desktop_autofill.cjs. Edit shared extension modules / autofill-desktop.js.\n'+license.replace(/\*\//g,'* /')+'\n'+notice.replace(/\*\//g,'* /')+'\n*/\n(function(){if(window.__XIAOMAI_FILL__)return;\n'+parts.join('\n')+'\n'+ui+'\n})();\n';
new vm.Script(out);
fs.writeFileSync(path.join(root,'campus-job-desktop/src-tauri/autofill.js'),out);
console.log('Desktop autofill: '+modules.length+' shared modules, '+Buffer.byteLength(out)+' bytes');
