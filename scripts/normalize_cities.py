# 合并：省级也算有效
VALID = PROVINCES | CITIES

def strip_suffix(s):
    """去尾部行政区划后缀"""
    for suf in ('市', '区', '县', '镇', '乡', '村', '旗', '盟', '州'):
        if s.endswith(suf) and len(s) > 2:
            s = s[:-1]
    return s

def normalize_city(raw):
    if not raw:
        return ''
    s = raw.strip().replace(' ', '').replace('　', '')
    if not s:
        return ''
    # 错别字(精确匹配, 避免"内蒙古"里的"内蒙"被误替换)
    for k, v in TYPO.items():
        if s == k:
            s = v
            break
    # 远程
    if is_remote(s):
        return '远程/线上'
    # 全国
    if is_nationwide(s):
        return '全国'
    # 大区
    if s in REGIONS:
        return '全国'
    # 海外
    if s in FOREIGN:
        return '海外'
    # 非城市
    if is_invalid(s):
        return '其他'
    # 后缀归并
    t = strip_suffix(s)
    if t in VALID:
        return t
    if s in VALID:
        return s
    # 「省+市」→ 市（山东济南 → 济南）
    for prov in PROVINCES:
        if s.startswith(prov) and len(s) > len(prov) and s[len(prov):] in VALID:
            return s[len(prov):]
    # 「直辖市+区/新区」→ 直辖市（北京海淀区 → 北京）
    for dc in ('北京', '上海', '天津', '重庆'):
        if s.startswith(dc) and s != dc:
            return dc
    # 含「省」字的是省级(如"四川省" → 四川, "浙江省" → 浙江)
    if s.endswith('省') and s[:-1] in PROVINCES:
        return s[:-1]
    if s.endswith('市') and s[:-1] in PROVINCES:
        return s[:-1]
    # 含「区/县/路/街道」等 → 尝试「城市名前缀」归并（深圳福田区 → 深圳），否则其他
    if any(k in s for k in ('区', '县', '新区', '街道', '大道', '大厦', '园区', '校区', '路')):
        for city in sorted(CITIES, key=len, reverse=True):
            if s.startswith(city) and len(s) > len(city):
                return city
        return '其他'
    # 剩余无法识别 → 其他
    return '其他'

def main():
    # 导出 id, cities
    out = subprocess.check_output(
        ['mysql', '-N', '--default-character-set=utf8mb4', '-uroot', '-pCampusJob@2026',
         'campus_job', '-e', 'SELECT id, cities FROM job'],
        stderr=subprocess.DEVNULL).decode('utf-8')
    rows = []
    changed = 0
    stats = {}
    for line in out.splitlines():
        line = line.rstrip('\n')
        if '\t' not in line:
            continue
        jid, cities = line.split('\t', 1)
        if not cities or cities == 'NULL':
            continue
        parts = [x.strip() for x in cities.split(',') if x.strip()]
        new_parts = []
        for p in parts:
            np = normalize_city(p)
            if np and np not in new_parts:
                new_parts.append(np)
        new_cities = ','.join(new_parts)
        if new_cities != cities:
            changed += 1
            rows.append((jid, new_cities))
        for np in new_parts:
            stats[np] = stats.get(np, 0) + 1
    # 生成 UPDATE 并执行
    if rows:
        with open('/tmp/city_update.sql', 'w', encoding='utf-8') as f:
            for jid, cities in rows:
                esc = cities.replace('\\', '\\\\').replace("'", "''")
                f.write(f"UPDATE job SET cities='{esc}' WHERE id={jid};\n")
        subprocess.check_call(
            ['mysql', '--default-character-set=utf8mb4', '-uroot', '-pCampusJob@2026',
             'campus_job'], stdin=open('/tmp/city_update.sql', encoding='utf-8'))
    print(f'总记录处理: {sum(1 for _ in out.splitlines())}, 变更记录: {changed}')
    print(f'归一化后城市种类: {len(stats)}')
    top = sorted(stats.items(), key=lambda x: -x[1])[:60]
    for k, v in top:
        print(f'{v}\t{k}')

if __name__ == '__main__':
    main()
