def normalize_industry(raw):
    if raw is None:
        return '其他', ''
    s = str(raw).strip()
    for k, v in TYPO_FIX.items():
        if k in s:
            s = s.replace(k, v)
    # 精确多值覆盖
    if s in MULTI_INDUSTRY_OVERRIDE:
        return MULTI_INDUSTRY_OVERRIDE[s], s
    if s in INDUSTRY_MAP:
        return INDUSTRY_MAP[s], s
    # 含逗号/斜杠的多值 -> 逐个映射
    if re.search(r'[,，]', s):
        parts = [p.strip() for p in re.split(r'[,，]', s) if p.strip()]
        mapped = []
        for p in parts:
            m = INDUSTRY_MAP.get(p)
            if m and m not in mapped:
                mapped.append(m)
        if mapped:
            return ','.join(mapped), s
    # 无法映射 -> 其他
    return '其他', s

