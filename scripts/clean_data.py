# 6. 网申截止日期解析
# ============================================================
ROLLING_WORDS = ('招满即止', '尽快投递', '额满即止')

def parse_deadline(raw):
    """返回 (deadline文本, deadline_date字符串YYYY-MM-DD或'')"""
    if raw is None:
        return '招满即止', ''
    s = str(raw).strip()
    for k, v in TYPO_FIX.items():
        s = s.replace(k, v)
    s = s.strip().strip('。:：')
    # 滚动截止
    if any(w in s for w in ('招满即止', '尽快投递', '额满即止')):
        return '招满即止', ''
    if s in ('', '未找到'):
        return '招满即止', ''

    # 处理 "2026/410" 这类漏斜杠 -> 无法可靠解析, 跳过
    # 月份模糊: 2026/6月, 2026/6月底, 2026/6月初, 2026/6月上旬
    m = re.match(r'^(20\d{2})年?[/.-]?(\d{1,2})月(底|初|上旬|中旬|下旬)?$', s)
    if m:
        y, mo = int(m.group(1)), int(m.group(2))
        suffix = m.group(3) or ''
        day = 30 if suffix == '底' else (1 if suffix in ('初', '上旬') else (15 if suffix in ('中旬',) else 28))
        return f'{y:04d}-{mo:02d}-{day:02d}', f'{y:04d}-{mo:02d}-{day:02d}'
    m = re.match(r'^(\d{1,2})月(\d{1,2})日$', s)  # 无年份
    if m:
        return f'2026-{int(m.group(1)):02d}-{int(m.group(2)):02d}', f'2026-{int(m.group(1)):02d}-{int(m.group(2)):02d}'
    m = re.match(r'^(\d{1,2})月(底|初|上旬|中旬|下旬)$', s)
    if m:
        mo = int(m.group(1))
        suffix = m.group(2)
        day = 30 if suffix == '底' else (1 if suffix in ('初', '上旬') else (15 if suffix == '中旬' else 28))
        return f'2026-{mo:02d}-{day:02d}', f'2026-{mo:02d}-{day:02d}'
    # 年月日, 支持 / . - 及中文年月日, 及两位年份
    m = re.match(r'^(\d{2,4})[年/.\-](\d{1,2})[月/.\-](\d{1,2})日?$', s)
    if m:
        y = int(m.group(1))
        y = y + 2000 if y < 100 else y
        return f'{y:04d}-{int(m.group(2)):02d}-{int(m.group(3)):02d}', f'{y:04d}-{int(m.group(2)):02d}-{int(m.group(3)):02d}'
    # 只有年月
    m = re.match(r'^(20\d{2})[/.-](\d{1,2})$', s)
    if m:
        y, mo = int(m.group(1)), int(m.group(2))
        return f'{y:04d}-{mo:02d}-28', f'{y:04d}-{mo:02d}-28'
    # 无法解析 -> 保留原文作为文本, 无日期
    return s, ''

