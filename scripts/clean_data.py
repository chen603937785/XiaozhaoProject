def normalize_cities(raw):
    if not raw:
        return '', ''
    s = str(raw).strip()
    parts = [p.strip() for p in re.split(r'[,，、]', s) if p.strip()]
    out = []
    for p in parts:
        p = CITY_ALIAS.get(p, p)
        # 去除城市名里的空格
        p = re.sub(r'\s+', '', p)
        if p and p not in out:
            out.append(p)
    return ','.join(out), s

