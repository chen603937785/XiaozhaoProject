def normalize_recruit_types(raw):
    """拆分多值并映射到标准类型, 返回逗号分隔的排序列表"""
    if not raw:
        return '', raw or ''
    s = str(raw).strip()
    for k, v in TYPO_FIX.items():
        if k in s:
            s = s.replace(k, v)
    parts = re.split(r'[,，、/]', s)
    result = set()
    for p in parts:
        p = p.strip()
        if not p:
            continue
        std = RECRUIT_TYPE_MAP.get(p, p)  # 未知词原样保留
        result.add(std)
    # 按标准顺序排序
    ordered = [t for t in RECRUIT_TYPES if t in result]
    # 兜底：有未知类型未覆盖
    for r in result:
        if r not in ordered:
            ordered.append(r)
    return ','.join(ordered), s

