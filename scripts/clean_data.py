# 9.5 同名公司企业性质众数归一化
# ============================================================
# 优先级: 众数并列时, 编制类性质优先
NATURE_PRIORITY = ['央国企', '事业单位', '社会机构/公益组织', '民企', '外企/合资', '其他']

def normalize_company_nature(records):
    """同名公司若企业性质标注不一致, 取出现最多的性质(众数), 并列时按编制优先级"""
    counter_map = {}
    for rec in records:
        name = rec[1]
        if not name:
            continue
        counter_map.setdefault(name, Counter())[rec[6]] += 1

    changed = 0
    for rec in records:
        name = rec[1]
        if not name:
            continue
        counter = counter_map[name]
        if len(counter) <= 1:
            continue
        max_cnt = max(counter.values())
        candidates = [n for n, c in counter.items() if c == max_cnt]
        majority = next((n for n in NATURE_PRIORITY if n in candidates), candidates[0])
        if rec[6] != majority:
            rec[6] = majority
            changed += 1
    return changed

