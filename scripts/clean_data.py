# 4. 招聘对象 -> 届别区间 (grade_min, grade_max)
# ============================================================
def parse_grades(raw):
    """返回 (grade_min, grade_max, target_raw)。
    - 正常区间: (26, 29)
    - 不限届: (0, 99)
    - 无法解析: (None, None)
    """
    if raw is None:
        return None, None, ''
    s = str(raw).strip()
    if '不限' in s:
        return 0, 99, s
    # 提取 21-30 之间的两位数字作为届别
    nums = sorted(set(int(n) for n in re.findall(r'\d+', s) if 21 <= int(n) <= 30))
    if nums:
        return min(nums), max(nums), s
    # 有文字但无届别数字(往届生/研究生/留学生等)
    return None, None, s

