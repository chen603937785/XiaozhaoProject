-- 待办功能迁移 SQL (MySQL 8.0)
CREATE TABLE IF NOT EXISTS todo (
  id           BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id      BIGINT UNSIGNED NOT NULL COMMENT '用户id',
  plan_id      BIGINT UNSIGNED NULL COMMENT '归属求职计划',
  job_id       BIGINT UNSIGNED NULL COMMENT '关联岗位',
  title        VARCHAR(255) NOT NULL COMMENT '待办名称',
  description  VARCHAR(500) NULL COMMENT '备注',
  todo_type    VARCHAR(20) NOT NULL DEFAULT 'CUSTOM' COMMENT 'APPLICATION/MATERIAL/ASSESSMENT/INTERVIEW/FOLLOW_UP/CUSTOM',
  priority     VARCHAR(20) NOT NULL DEFAULT 'NORMAL' COMMENT 'URGENT/IMPORTANT/NORMAL',
  status       VARCHAR(20) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/COMPLETED',
  due_at       DATETIME NULL COMMENT '截止时间',
  source       VARCHAR(20) NOT NULL DEFAULT 'USER' COMMENT 'SYSTEM/USER',
  completed_at DATETIME NULL COMMENT '完成时间',
  created_at   DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at   DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_user (user_id),
  KEY idx_user_plan (user_id, plan_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='待办表';
